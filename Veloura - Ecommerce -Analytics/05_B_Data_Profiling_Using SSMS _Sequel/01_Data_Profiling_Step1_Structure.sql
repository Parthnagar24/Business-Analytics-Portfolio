--ROW COUNT :

SELECT 
	'staging.customers' AS Table_name,
	COUNT(*) AS Row_Count
FROM staging.customers  

UNION ALL

SELECT
	'staging.products',
	COUNT(*) 
FROM staging.products

UNION ALL

SELECT 
	'staging.orders',
	COUNT(*)
FROM staging.orders  

UNION ALL

SELECT 
	'staging.order_details',
	COUNT(*) 
FROM staging.order_details

UNION ALL

SELECT 
	'staging.reviews',
	COUNT(*)  
FROM staging.reviews

UNION ALL

SELECT 
	'staging.returns',
	COUNT(*)  
FROM staging.returns

UNION ALL 

SELECT
	'staging.promotions',
	COUNT(*) 
FROM staging.promotions



